import assert from 'node:assert/strict';
import {parseCatalog,search,offersFor,safeUrl,shoeSize} from '../lib/catalog.ts';
const now=Date.now();
const v={size:'42',price:10000,available:true};
const o={sourceId:'newbalance',url:'https://www.newbalance.com.tr/test',checkedAt:new Date(now).toISOString(),variants:[v,{...v,size:'43',price:12000}]};
const p={id:'a'.repeat(20),name:'9060 Gri',brand:'NEW BALANCE',color:'Gri',code:'U9060',image:'https://example.test/a.jpg',offers:[o]};
const data={generatedAt:new Date(now).toISOString(),sources:[{id:'newbalance',name:'New Balance',status:'ok'}],products:[p]};
assert.equal(parseCatalog(data),data);
assert.equal(search(data,'9060','', ['43'],now)[0].price,12000);
assert.equal(search(data,'9060','', ['44'],now).length,0);
assert.equal(search(data,'asıcs','', ['42'],now).length,0);
assert.equal(search(data,'','', [],now).length,0);
assert.equal(search(data,'','', ['42','43'],now)[0].price,10000);
assert.equal(search(data,'','OTHER', ['42'],now).length,0);
assert.equal(offersFor(p,data,[],now+86400000).length,0);
assert.equal(safeUrl('javascript:alert(1)'), '');
assert.equal(safeUrl('https://attacker.example',true),'');
assert.equal(safeUrl('https://www.beymen.com/tr/p_shoe_123',true),'https://www.beymen.com/tr/p_shoe_123');
assert.equal(safeUrl('https://www.beymen.com.attacker.example/tr/p_shoe_123',true),'');
assert.throws(()=>parseCatalog({...data,products:[{...p,offers:[{...o,variants:[{...v,price:1.2}]}]}]}));
assert.equal(offersFor(p,{...data,sources:[{...data.sources[0],status:'error'}]},[],now).length,0);
for (const [value,expected] of [['44,5','44.5'],['36⅔','36 ⅔'],['35','35'],['50','50'],['50.5',''],['34',''],['S',''],['One Size',''],['12 Ay',''],['US 8',''],['','']]) assert.equal(shoeSize(value),expected,value);
o.variants.push({...v,size:'44.5',price:8000},{...v,size:'45',price:100,available:false},{...v,size:'46',price:1});
assert.equal(search(data,'','',['42','43','44,5','46'],now)[0].price,8000);
assert.equal(search(data,'','',['45'],now).length,0);
o.variants.push({...v,size:'36⅔',price:9000});
assert.equal(search(data,'','',['36 ⅔'],now)[0].price,9000);
console.log('Catalog: parsing, size price, stale data, failed source and URL checks passed.');
